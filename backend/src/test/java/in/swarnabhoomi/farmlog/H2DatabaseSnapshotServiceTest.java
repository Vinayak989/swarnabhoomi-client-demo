package in.swarnabhoomi.farmlog;

import static org.assertj.core.api.Assertions.assertThat;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.sql.DriverManager;
import java.time.Instant;
import java.util.HexFormat;
import java.util.zip.ZipFile;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.autoconfigure.jdbc.DataSourceProperties;
import org.springframework.mock.web.MockHttpServletRequest;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class H2DatabaseSnapshotServiceTest {
    @TempDir Path directory;

    @Test void onlineSnapshotRestoresAllTablesUnicodeAndPhotoBytesWithoutSourcePassword() throws Exception {
        String sourceUrl = "jdbc:h2:file:" + directory.resolve("source").toString().replace('\\', '/');
        String name = "शेतकरीचे शेत O'Brien 🌱";
        byte[] photo = new byte[150_000]; new java.util.Random(42).nextBytes(photo);
        var source = new DriverManagerDataSource(sourceUrl, "sa", "test-source-password");
        try (var connection = source.getConnection(); var sql = connection.createStatement()) {
            sql.execute("CREATE TABLE person(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(300))");
            sql.execute("CREATE TABLE photo(id BIGINT PRIMARY KEY, owner_id BIGINT REFERENCES person(id), photo_data BLOB)");
            try (var insert = connection.prepareStatement("INSERT INTO person(id,name) VALUES(42,?)")) { insert.setString(1, name); insert.executeUpdate(); }
            try (var insert = connection.prepareStatement("INSERT INTO photo VALUES(7,42,?)")) { insert.setBytes(1, photo); insert.executeUpdate(); }
        }
        var properties = new DataSourceProperties(); properties.setUrl(sourceUrl); properties.setUsername("sa"); properties.setPassword("test-source-password");
        var service = new H2DatabaseSnapshotService(source, properties, new ObjectMapper(), directory.resolve("backups").toString());
        var snapshot = service.create();
        assertThat(snapshot.counts()).containsEntry("person", 1L).containsEntry("photo", 1L);
        assertThat(snapshot.sha256()).isEqualTo(HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(snapshot.archive()))));
        Path script = directory.resolve("restore.sql");
        try (ZipFile zip = new ZipFile(snapshot.archive().toFile())) {
            assertThat(zip.getEntry("h2-native-backup.zip")).isNotNull();
            assertThat(zip.getEntry("manifest.json")).isNotNull();
            try (var input = zip.getInputStream(zip.getEntry("h2-snapshot.sql"))) { Files.copy(input, script); }
        }
        try (var restored = DriverManager.getConnection("jdbc:h2:mem:restored_snapshot", "sa", ""); var sql = restored.createStatement()) {
            sql.execute("RUNSCRIPT FROM '" + script.toString().replace('\\', '/').replace("'", "''") + "' CHARSET 'UTF-8'");
            try (var rows = sql.executeQuery("SELECT name,photo_data FROM person JOIN photo ON person.id=photo.owner_id")) {
                assertThat(rows.next()).isTrue(); assertThat(rows.getString(1)).isEqualTo(name); assertThat(rows.getBytes(2)).isEqualTo(photo);
            }
        }
        try (var connection = source.getConnection(); var sql = connection.createStatement()) { sql.execute("INSERT INTO person(name) VALUES('Later row')"); }
        assertThat(service.create()).isSameAs(snapshot);
        assertThat(snapshot.counts().get("person")).isEqualTo(1L);
    }

    @Test void exportCapabilityIsLimitedToOneRouteAndExpires() {
        String token = "temporary-backup-capability-for-tests-only-000001";
        var access = new DatabaseExportAccess(token, Instant.now().plusSeconds(300).toString());
        var request = new MockHttpServletRequest("POST", DatabaseExportAccess.PATH); request.addHeader("Authorization", "Bearer " + token);
        assertThat(access.isAuthorized(request)).isTrue();
        request.setRequestURI("/api/entries"); assertThat(access.isAuthorized(request)).isFalse();
        request.setRequestURI(DatabaseExportAccess.PATH); request.setMethod("GET"); assertThat(access.isAuthorized(request)).isFalse();
        request.setMethod("POST");
        assertThat(new DatabaseExportAccess(token, Instant.now().minusSeconds(1).toString()).isAuthorized(request)).isFalse();
        assertThat(new DatabaseExportAccess("", "").isAuthorized(request)).isFalse();
        request.removeHeader("Authorization"); request.addHeader("Authorization", "Bearer incorrect"); assertThat(access.isAuthorized(request)).isFalse();
    }
}
